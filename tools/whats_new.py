#!/usr/bin/env python3
"""What's new in the archive: the latest uploads, newest first.

    python tools/whats_new.py                     # print catalog/WHATS_NEW.md
    python tools/whats_new.py --since 2026-11-19  # release notes: everything added after that day

build_catalog.py writes catalog/WHATS_NEW.md with this on every run, and
build_site.py writes the gallery's feed (feed.xml) with it. Both read the
catalog's "added" column: the day each motion first appeared in the catalog.

Each motion is listed as one of:
    new sign         nothing else in the archive has this name
    another version  the sign was already here; this is an extra version of it
                     (Alt, 2H, another take; see FAQ 18)
    re-recorded      a newer recording under the same name; the old one is superseded

Only the Python standard library is needed.
"""

from __future__ import annotations

import argparse
import collections
import csv
import datetime as dt
import html
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

SHOW_DAYS = 15  # upload days listed in WHATS_NEW.md
FEED_DAYS = 20  # upload days in the feed


def pretty(day: str) -> str:
    d = dt.date.fromisoformat(day)
    return f"{d.day} {d:%B %Y}"


def describe(rows: list[dict]) -> list[dict]:
    """Current motions with an added date, newest first, each with its kind and a note."""
    import build_catalog as bc

    slugs = bc.sign_slugs(r["id"] for r in rows)
    replaced = collections.defaultdict(list)
    for r in rows:
        if r.get("superseded_by"):
            replaced[r["superseded_by"]].append(r)
    by_group = collections.defaultdict(list)
    current = [r for r in rows if r.get("status") == "current" and r.get("added")]
    for r in current:
        by_group[(r["collection"], r["group"].lower())].append(r)

    out = []
    for r in current:
        old = replaced.get(r["folder"])
        earlier = [x for x in by_group[(r["collection"], r["group"].lower())]
                   if x is not r and x["added"] < r["added"]]
        if old:
            dates = sorted(x["date"] for x in old if x["date"])
            kind, note = "re-recorded", f"re-recorded, replaces the {pretty(dates[-1])} version" if dates else "re-recorded"
        elif earlier:
            kind, note = "version", f"another version of {r['group']}"
        else:
            kind, note = "new", "new sign"
        name = r.get("display_name") or r["name"]
        if r["collection"] == "Fingerspelling":
            note += " (fingerspelling)"
        out.append({**r, "kind": kind, "note": note, "shown": name,
                    "url": f"{bc.GALLERY}sign/{slugs[r['id']]}/"})
    out.sort(key=lambda r: (r["added"], r["shown"].lower()), reverse=True)
    return out


def by_day(items: list[dict]) -> list[tuple[str, list[dict]]]:
    days = collections.defaultdict(list)
    for it in items:
        days[it["added"]].append(it)
    return [(d, sorted(days[d], key=lambda r: r["shown"].lower())) for d in sorted(days, reverse=True)]


def counts(items: list[dict]) -> str:
    c = collections.Counter(it["kind"] for it in items)
    parts = []
    if c["new"]:
        parts.append(f"{c['new']} new sign" + ("s" if c["new"] != 1 else ""))
    if c["version"]:
        parts.append(f"{c['version']} more version" + ("s" if c["version"] != 1 else "") + " of signs already here")
    if c["re-recorded"]:
        parts.append(f"{c['re-recorded']} re-recorded")
    return ", ".join(parts)


def render(rows: list[dict], show_days: int = SHOW_DAYS) -> str:
    """catalog/WHATS_NEW.md"""
    import build_catalog as bc

    days = by_day(describe(rows))
    lines = [
        "# What's new",
        "",
        "The newest motions in the archive, by the day they were uploaded. "
        "Generated by `tools/build_catalog.py`; don't edit by hand.",
        "",
        f"- **In the gallery:** [newest first]({bc.GALLERY}?sort=new)",
        f"- **Follow along:** add the [feed]({bc.GALLERY}feed.xml) to a feed reader, or on GitHub use "
        "**Watch → Custom → Releases** to hear about new download packs.",
        "- **Everything else:** the `added` column in [catalog.csv](catalog.csv). "
        "Motions uploaded before 24 November 2026 are dated by the date in their folder name.",
        "",
    ]
    if not days:
        lines.append("Nothing yet.")
    for day, items in days[:show_days]:
        n = len(items)
        lines += [f"## {pretty(day)}", "", f"{n} motion{'s' if n != 1 else ''}: {counts(items)}.", ""]
        lines += [f"- [{it['shown']}]({it['url']}): {it['note']}" for it in items]
        lines.append("")
    if len(days) > show_days:
        lines.append(f"Older uploads are in [catalog.csv](catalog.csv) ({len(days) - show_days} more upload days).")
    return "\n".join(lines).rstrip() + "\n"


def release_notes(rows: list[dict], since: str, until: str = "") -> str:
    """Markdown for a release: everything added after `since` (and up to `until`)."""
    items = [it for it in describe(rows) if it["added"] > since and (not until or it["added"] <= until)]
    if not items:
        return f"No motions added after {since}.\n"
    head = f"**{len(items)} motion{'s' if len(items) != 1 else ''} added since {pretty(since)}:** {counts(items)}."
    lines = [head, ""]
    sections = [("new", "New signs"), ("version", "More versions of signs already here"),
                ("re-recorded", "Re-recorded")]
    for kind, title in sections:
        group = sorted((it for it in items if it["kind"] == kind), key=lambda r: r["shown"].lower())
        if not group:
            continue
        lines += [f"### {title}", ""]
        for it in group:
            extra = "" if kind == "new" else f" ({it['note'].removeprefix('re-recorded, ')})"
            lines.append(f"- [{it['shown']}]({it['url']}){extra}")
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def atom(rows: list[dict], base_url: str, feed_days: int = FEED_DAYS) -> str:
    """An Atom feed with one entry per upload day."""
    days = by_day(describe(rows))[:feed_days]
    esc = html.escape
    updated = f"{days[0][0]}T00:00:00Z" if days else "2026-11-24T00:00:00Z"
    out = [
        '<?xml version="1.0" encoding="utf-8"?>',
        '<feed xmlns="http://www.w3.org/2005/Atom">',
        "  <title>Sign Language Mocap Archive: new signs</title>",
        "  <subtitle>Motion capture of American Sign Language, newest uploads first.</subtitle>",
        f'  <link rel="self" href="{esc(base_url)}feed.xml"/>',
        f'  <link rel="alternate" href="{esc(base_url)}?sort=new"/>',
        f"  <id>{esc(base_url)}feed.xml</id>",
        f"  <updated>{updated}</updated>",
        "  <author><name>Studio Galt</name></author>",
    ]
    for day, items in days:
        n = len(items)
        names = ", ".join(it["shown"] for it in items[:6]) + (f" and {n - 6} more" if n > 6 else "")
        body = f"<p>{esc(counts(items))}.</p><ul>" + "".join(
            f'<li><a href="{esc(it["url"])}">{esc(it["shown"])}</a>: {esc(it["note"])}</li>' for it in items) + "</ul>"
        out += [
            "  <entry>",
            f"    <title>{esc(f'{n} added on {pretty(day)}: {names}')}</title>",
            f'    <link href="{esc(base_url)}?sort=new"/>',
            f"    <id>{esc(base_url)}new/{day}</id>",
            f"    <updated>{day}T00:00:00Z</updated>",
            f'    <content type="html">{esc(body)}</content>',
            "  </entry>",
        ]
    out.append("</feed>")
    return "\n".join(out) + "\n"


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--since", help="release notes for motions added after this day (YYYY-MM-DD)")
    ap.add_argument("--until", default="", help="with --since: only up to this day")
    ap.add_argument("--catalog", default="", help="catalog.csv to read (default: the repository's)")
    args = ap.parse_args(argv)

    import build_catalog as bc
    path = Path(args.catalog) if args.catalog else bc.repo_root() / "catalog" / "catalog.csv"
    with open(path, newline="", encoding="utf-8") as fh:
        rows = list(csv.DictReader(fh))
    if rows and "added" not in rows[0]:
        print(f"{path} has no 'added' column yet; run tools/build_catalog.py first.", file=sys.stderr)
        return 1
    if args.since:
        dt.date.fromisoformat(args.since)
        sys.stdout.write(release_notes(rows, args.since, args.until))
    else:
        sys.stdout.write(render(rows))
    return 0


if __name__ == "__main__":
    sys.exit(main())
